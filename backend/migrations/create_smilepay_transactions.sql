COMMENT ON TABLE smilepay_transactions IS 'Tracks all payment transactions through SmilePay gateway';
COMMENT ON COLUMN smilepay_transactions.payment_type IS 'Type of payment: subscription, campaign, booking, wallet, cart, collaboration';
COMMENT ON COLUMN smilepay_transactions.order_reference IS 'Unique order reference generated by our system';
COMMENT ON COLUMN smilepay_transactions.transaction_reference IS 'Transaction reference returned by SmilePay';
COMMENT ON COLUMN smilepay_transactions.payment_method IS 'Payment method used: ecocash, innbucks, visa, mastercard, smilecash, omari';
COMMENT ON COLUMN smilepay_transactions.status IS 'Payment status: PENDING, PAID, FAILED, CANCELED';
COMMENT ON COLUMN smilepay_transactions.payment_code IS 'Payment code for Innbucks transactions';
COMMENT ON COLUMN smilepay_transactions.otp_required IS 'Whether OTP is required for this payment method';
